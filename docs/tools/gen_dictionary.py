#!/usr/bin/env python3
"""Builds docs/data-dictionary.md from the LIVE schema catalog. Usage: python3 docs/tools/gen_dictionary.py <dolt-data-dir>"""
import json, subprocess, sys
from collections import defaultdict
d = sys.argv[1]
def q(sql):
    return json.loads(subprocess.run(["dolt","sql","-r","json","-q",sql],cwd=d,capture_output=True,text=True,check=True).stdout).get("rows",[])
S="table_schema='examsphere_db'"
cols=q(f"SELECT TABLE_NAME,COLUMN_NAME,COLUMN_TYPE,IS_NULLABLE,COLUMN_DEFAULT,COLUMN_KEY,EXTRA,COLUMN_COMMENT FROM information_schema.columns WHERE {S} ORDER BY TABLE_NAME,ORDINAL_POSITION")
fk={(r["TABLE_NAME"],r["COLUMN_NAME"]):f'{r["REFERENCED_TABLE_NAME"]}.{r["REFERENCED_COLUMN_NAME"]}' for r in q(f"SELECT TABLE_NAME,COLUMN_NAME,REFERENCED_TABLE_NAME,REFERENCED_COLUMN_NAME FROM information_schema.key_column_usage WHERE {S} AND REFERENCED_TABLE_NAME IS NOT NULL")}
pk=defaultdict(set)
for r in q(f"SELECT TABLE_NAME,COLUMN_NAME FROM information_schema.key_column_usage WHERE {S} AND CONSTRAINT_NAME='PRIMARY'"): pk[r["TABLE_NAME"]].add(r["COLUMN_NAME"])
views={next(v for k,v in r.items() if k.startswith("Tables_in")) for r in q("SHOW FULL TABLES FROM examsphere_db WHERE Table_type='VIEW'")}
vcols={v:[r.get("Field") or r.get("COLUMN_NAME") for r in q(f"SHOW COLUMNS FROM `examsphere_db`.`{v}`")] for v in views}
by=defaultdict(list)
for r in cols: by[r["TABLE_NAME"]].append(r)
esc=lambda x:str(x).replace("|","\\|") if x is not None else ""
out=["# Data dictionary (generated from the implemented schema)\n","Generated by `docs/tools/gen_dictionary.py` from `information_schema`. Key column: PK primary key, FK foreign key (target shown). Business rules and indexes: [database-design.md](database-design.md).\n"]
for t in sorted(by):
    if t in views: continue
    out+= [f"## `{t}`\n","| Column | Type | Null | Default | Key | Notes |","|---|---|---|---|---|---|"]
    for r in by[t]:
        c=r["COLUMN_NAME"]; key=("PK" if c in pk[t] else "")+(" FK→"+fk[(t,c)] if (t,c) in fk else "")
        notes="; ".join(x for x in [r.get("COLUMN_COMMENT"),("generated column" if any(k in (r.get("EXTRA") or "").upper() for k in ("STORED GENERATED","VIRTUAL GENERATED")) else ""),("auto-increment" if "auto_increment" in (r.get("EXTRA") or "").lower() else "")] if x)
        out.append(f'| `{c}` | `{esc(r["COLUMN_TYPE"])}` | {"YES" if r["IS_NULLABLE"]=="YES" else "NO"} | {esc(r.get("COLUMN_DEFAULT"))} | {key.strip()} | {esc(notes)} |')
    out.append("")
out+=["## Views\n","| View | Columns |","|---|---|"]
for v in sorted(views): out.append(f'| `{v}` | {", ".join("`"+c+"`" for c in vcols[v])} |')
open("docs/data-dictionary.md","w").write("\n".join(out)+"\n")
print(len(by), "objects")
