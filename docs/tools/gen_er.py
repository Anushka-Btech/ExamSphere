#!/usr/bin/env python3
"""Builds docs/er-diagram.md (Mermaid ER diagram + relationship table) from the LIVE schema catalog, so the diagram cannot drift
from the SQL. Usage: python3 docs/tools/gen_er.py <dolt-data-dir>    (works on any MySQL 8 too: swap the query runner)."""
import json, subprocess, sys
from collections import defaultdict
from pathlib import Path

data_dir = sys.argv[1]
def q(sql):
    r = subprocess.run(["dolt", "sql", "-r", "json", "-q", sql], cwd=data_dir, capture_output=True, text=True, check=True)
    return json.loads(r.stdout)["rows"]

S = "table_schema='examsphere_db'"
cols = q(f"SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, IS_NULLABLE, ORDINAL_POSITION FROM information_schema.columns WHERE {S} ORDER BY TABLE_NAME, ORDINAL_POSITION")
kcu = q(f"SELECT TABLE_NAME, COLUMN_NAME, CONSTRAINT_NAME, REFERENCED_TABLE_NAME, REFERENCED_COLUMN_NAME, ORDINAL_POSITION FROM information_schema.key_column_usage WHERE {S} ORDER BY TABLE_NAME, CONSTRAINT_NAME, ORDINAL_POSITION")
uniq = {(r["TABLE_NAME"], r["CONSTRAINT_NAME"]) for r in q(f"SELECT TABLE_NAME, CONSTRAINT_NAME FROM information_schema.table_constraints WHERE {S} AND CONSTRAINT_TYPE='UNIQUE'")}
rules = {r["CONSTRAINT_NAME"]: r["DELETE_RULE"] for r in q(f"SELECT CONSTRAINT_NAME, DELETE_RULE FROM information_schema.referential_constraints WHERE CONSTRAINT_SCHEMA='examsphere_db'")}

tables = defaultdict(list)
nullable = {}
for r in cols:
    tables[r["TABLE_NAME"]].append((r["COLUMN_NAME"], r["DATA_TYPE"]))
    nullable[(r["TABLE_NAME"], r["COLUMN_NAME"])] = r["IS_NULLABLE"] == "YES"
pk, fk_cols, uq_cols, fks, uq_sets = defaultdict(list), defaultdict(set), defaultdict(set), defaultdict(lambda: defaultdict(list)), defaultdict(lambda: defaultdict(list))
for r in kcu:
    t, c, k = r["TABLE_NAME"], r["COLUMN_NAME"], r["CONSTRAINT_NAME"]
    if k == "PRIMARY": pk[t].append(c)
    elif r.get("REFERENCED_TABLE_NAME"): fks[t][k].append((c, r["REFERENCED_TABLE_NAME"], r["REFERENCED_COLUMN_NAME"])); fk_cols[t].add(c)
    elif (t, k) in uniq: uq_sets[t][k].append(c)
for t, sets in uq_sets.items():
    for k, cs in sets.items():
        if len(cs) == 1: uq_cols[t].add(cs[0])

out = ["# ER diagram (generated from the implemented schema)\n",
       "Generated by `docs/tools/gen_er.py` from `information_schema`, so every table, column, key and relationship below exists in `database/01_schema.sql`.",
       "Key: **PK** primary key, **FK** foreign key, **UK** single-column unique. Composite unique constraints (for example `(exam_id, student_id)`) are listed in `database-design.md`.\n",
       "```mermaid", "erDiagram"]
rel_rows = []
for t in sorted(fks):
    for k, parts in sorted(fks[t].items()):
        cs = [p[0] for p in parts]; parent = parts[0][1]
        one_to_one = set(cs) == set(pk[t])                      # PK is also the FK: specialisation (profile) table
        if one_to_one: sym, card = "||--o|", "1 : 0..1"
        elif len(cs) == 1 and (t, k) and cs[0] in uq_cols[t]: sym, card = "||--o|", "1 : 0..1"
        elif any(nullable[(t, c)] for c in cs): sym, card = "|o--o{", "0..1 : N"
        else: sym, card = "||--o{", "1 : N"
        out.append(f'  {parent} {sym} {t} : "{k}"')
        rel_rows.append((parent, t, ", ".join(cs), card, rules.get(k, "?"), k))
for t in sorted(tables):
    out.append(f"  {t} {{")
    for c, d in tables[t]:
        tags = [x for x, on in (("PK", c in pk[t]), ("FK", c in fk_cols[t]), ("UK", c in uq_cols[t])) if on]
        out.append(f"    {d} {c}" + (f" {','.join(tags)}" if tags else ""))
    out.append("  }")
out += ["```\n", "## Relationships and deletion rules\n",
        "| Parent (one) | Child | Foreign key column(s) | Cardinality (parent : child) | ON DELETE | Constraint |", "|---|---|---|---|---|---|"]
out += [f"| `{p}` | `{c}` | `{cols_}` | {card} | {rule} | `{k}` |" for p, c, cols_, card, rule, k in sorted(rel_rows)]
out.append("\n`ON DELETE RESTRICT` blocks deleting a parent that still has children (history is preserved); `CASCADE` removes dependent rows that have no meaning alone (for example a user's session or an exam's question assignments); `SET NULL` keeps the log row but forgets the actor.")
Path(__file__).resolve().parent.parent.joinpath("er-diagram.md").write_text("\n".join(out) + "\n")
print(f"{len(tables)} tables, {len(rel_rows)} relationships")
