#!/usr/bin/env python3
"""Generates database/02_seed.sql deterministically (fixed RNG seed, fixed dates).

Run:  python3 database/tools/gen_seed.py
Passwords: the SQL contains __HASH_ADMIN__ / __HASH_FACULTY__ / __HASH_STUDENT__
placeholders. database/seed.js replaces them with real bcrypt hashes before
executing the file, so no plaintext password and no hash is committed.
"""
import random
from pathlib import Path

rng = random.Random(20261022)
out = []
q = lambda s: "'" + str(s).replace("\\", "\\\\").replace("'", "''") + "'"


def emit(s=""):
    out.append(s)


emit("-- Generated by database/tools/gen_seed.py - do not edit by hand.")
emit("USE examsphere_db;")
emit("SET FOREIGN_KEY_CHECKS = 0;")
for t in ["sessions", "audit_logs", "result_publications", "student_answers", "exam_attempts",
          "examination_questions", "examinations", "question_options", "questions",
          "faculty_subjects", "subjects", "faculty_profiles", "student_profiles", "users", "departments"]:
    emit(f"TRUNCATE TABLE {t};")
emit("SET FOREIGN_KEY_CHECKS = 1;\n")

# ---- departments
depts = [(1, "CSE", "Computer Science & Engineering"), (2, "IT", "Information Technology"),
         (3, "ECE", "Electronics & Communication")]
emit("INSERT INTO departments (department_id, code, name) VALUES")
emit(",\n".join(f"({i},{q(c)},{q(n)})" for i, c, n in depts) + ";\n")

# ---- users: 1 admin, 3 faculty, 12 students
users = [(1, "admin@examsphere.edu", "admin", "__HASH_ADMIN__", "Anita Deshmukh", "ADMIN")]
faculty = [(2, "meera.iyer@examsphere.edu", "meera.iyer", "Dr. Meera Iyer", "FAC001", 1, "Associate Professor"),
           (3, "rohan.verma@examsphere.edu", "rohan.verma", "Prof. Rohan Verma", "FAC002", 1, "Assistant Professor"),
           (4, "kavita.rao@examsphere.edu", "kavita.rao", "Dr. Kavita Rao", "FAC003", 2, "Professor")]
student_names = ["Aarav Sharma", "Diya Patel", "Kabir Singh", "Ishita Gupta", "Rahul Nair", "Sneha Reddy",
                 "Vihaan Mehta", "Ananya Joshi", "Arjun Kapoor", "Meera Pillai", "Yash Agarwal", "Tara Bose"]
# (department, semester) - 9 CSE sem 3, 3 IT sem 3
student_dept = [1] * 9 + [2] * 3
students = []
for i, name in enumerate(student_names):
    uid = 5 + i
    uname = name.lower().replace(" ", ".")
    students.append((uid, f"{uname}@student.examsphere.edu", uname, name, f"EN2024{i + 1:03d}",
                     student_dept[i], 3, f"2024-{6 + (i % 4):02d}-{5 + (i % 3):02d}"))

rows = [f"({u[0]},{q(u[1])},{q(u[2])},{q(u[3])},{q(u[4])},{q(u[5])},'ACTIVE')" for u in users]
rows += [f"({f[0]},{q(f[1])},{q(f[2])},'__HASH_FACULTY__',{q(f[3])},'FACULTY','ACTIVE')" for f in faculty]
rows += [f"({s[0]},{q(s[1])},{q(s[2])},'__HASH_STUDENT__',{q(s[3])},'STUDENT','ACTIVE')" for s in students]
# normalise first tuple layout (admin row has hash inline)
emit("INSERT INTO users (user_id, email, username, password_hash, full_name, role, status) VALUES")
user_rows = [f"({u[0]},{q(u[1])},{q(u[2])},{q(u[3])},{q(u[4])},{q(u[5])},'ACTIVE')" for u in users]
user_rows += [f"({f[0]},{q(f[1])},{q(f[2])},'__HASH_FACULTY__',{q(f[3])},'FACULTY','ACTIVE')" for f in faculty]
user_rows += [f"({s[0]},{q(s[1])},{q(s[2])},'__HASH_STUDENT__',{q(s[3])},'STUDENT','ACTIVE')" for s in students]
emit(",\n".join(user_rows) + ";\n")

emit("INSERT INTO faculty_profiles (user_id, employee_code, department_id, designation) VALUES")
emit(",\n".join(f"({f[0]},{q(f[4])},{f[5]},{q(f[6])})" for f in faculty) + ";\n")
emit("INSERT INTO student_profiles (user_id, enrollment_no, department_id, semester, enrollment_date) VALUES")
emit(",\n".join(f"({s[0]},{q(s[4])},{s[5]},{s[6]},{q(s[7])})" for s in students) + ";\n")

# ---- subjects
subjects = [(1, "CS301", "Database Management Systems", "Relational model, SQL, normalization, transactions.", 4, 3, 1),
            (2, "CS302", "Data Structures & Algorithms", "Arrays, linked lists, trees, graphs, sorting, complexity.", 4, 3, 1),
            (3, "CS303", "Operating Systems", "Processes, scheduling, memory management, deadlocks.", 3, 3, 1),
            (4, "IT304", "Computer Networks", "OSI model, TCP/IP, routing, application protocols.", 3, 3, 2),
            (5, "CS201", "Discrete Mathematics", "Logic, sets, relations, graph theory (archived syllabus).", 3, 2, 1)]
emit("INSERT INTO subjects (subject_id, code, name, description, credits, semester, department_id, status) VALUES")
emit(",\n".join(f"({s[0]},{q(s[1])},{q(s[2])},{q(s[3])},{s[4]},{s[5]},{s[6]},{q('ARCHIVED' if s[0] == 5 else 'ACTIVE')})"
                for s in subjects) + ";\n")

emit("INSERT INTO faculty_subjects (faculty_id, subject_id, assigned_on) VALUES")
emit(",\n".join(f"({a},{b},'2026-07-01')" for a, b in [(2, 1), (3, 2), (3, 1), (4, 3), (4, 4)]) + ";\n")

# ---- question bank: per subject 5 MCQ, 2 TF, 1 SHORT, 1 DESCRIPTIVE
# MCQ: (text, [options], correct_index, difficulty)
bank = {
    1: dict(author=2, mcq=[
        ("Which normal form removes partial dependencies on a composite key?", ["1NF", "2NF", "3NF", "BCNF"], 1, "EASY"),
        ("Which SQL clause filters groups after aggregation?", ["WHERE", "GROUP BY", "HAVING", "ORDER BY"], 2, "EASY"),
        ("Which isolation level prevents dirty reads but allows non-repeatable reads?", ["READ UNCOMMITTED", "READ COMMITTED", "REPEATABLE READ", "SERIALIZABLE"], 1, "MEDIUM"),
        ("A foreign key primarily enforces:", ["Entity integrity", "Referential integrity", "Domain integrity", "Query speed"], 1, "EASY"),
        ("Which index type does InnoDB use by default?", ["Hash", "B+ tree", "Bitmap", "R-tree"], 1, "MEDIUM")],
        tf=[("A table can have more than one PRIMARY KEY constraint.", False, "EASY"),
            ("ROLLBACK undoes all changes made since the last COMMIT in a transaction.", True, "EASY")],
        short=("Define a candidate key and give one example.", "A minimal set of attributes that uniquely identifies a row, e.g. enrollment_no in student_profiles.", "MEDIUM"),
        desc=("Explain the ACID properties of a transaction with a banking example.",
              "Atomicity: transfer fully happens or not. Consistency: balances stay valid. Isolation: concurrent transfers do not interfere. Durability: committed transfer survives a crash.", "HARD")),
    2: dict(author=3, mcq=[
        ("Worst-case time complexity of binary search on a sorted array is:", ["O(n)", "O(log n)", "O(n log n)", "O(1)"], 1, "EASY"),
        ("Which data structure uses LIFO order?", ["Queue", "Stack", "Heap", "Graph"], 1, "EASY"),
        ("Which traversal of a BST yields keys in sorted order?", ["Preorder", "Postorder", "Inorder", "Level order"], 2, "MEDIUM"),
        ("Which algorithm finds shortest paths with non-negative edge weights?", ["DFS", "Kruskal", "Dijkstra", "Prim"], 2, "MEDIUM"),
        ("Average-case time complexity of quicksort is:", ["O(n)", "O(n^2)", "O(n log n)", "O(log n)"], 2, "MEDIUM")],
        tf=[("A min-heap guarantees the root is the smallest element.", True, "EASY"),
            ("Merge sort is an in-place sorting algorithm.", False, "MEDIUM")],
        short=("State the difference between an array and a linked list.", "Arrays give O(1) random access with contiguous memory; linked lists allow O(1) insertion given a node but need O(n) access.", "EASY"),
        desc=("Describe how a hash table handles collisions using chaining and open addressing.",
              "Chaining stores colliding keys in a list per bucket; open addressing probes for another free slot (linear, quadratic, double hashing).", "HARD")),
    3: dict(author=4, mcq=[
        ("Which scheduling algorithm can cause starvation of long processes?", ["Round Robin", "FCFS", "Shortest Job First", "Multilevel feedback with aging"], 2, "MEDIUM"),
        ("A deadlock requires all of these EXCEPT:", ["Mutual exclusion", "Hold and wait", "Preemption", "Circular wait"], 2, "MEDIUM"),
        ("Which memory management technique can cause external fragmentation?", ["Paging", "Segmentation", "Demand paging", "Swapping with fixed frames"], 1, "MEDIUM"),
        ("A semaphore with initial value 1 is typically used as a:", ["Counting resource pool", "Mutex", "Barrier", "Timer"], 1, "EASY"),
        ("Which is NOT a process state?", ["Ready", "Running", "Waiting", "Compiling"], 3, "EASY")],
        tf=[("A thread shares the address space of its parent process.", True, "EASY"),
            ("Belady's anomaly can occur with the LRU page replacement policy.", False, "HARD")],
        short=("What is a context switch?", "Saving the state of the running process and loading the state of another so the CPU can be reallocated.", "EASY"),
        desc=("Compare paging and segmentation.",
              "Paging uses fixed-size frames and avoids external fragmentation; segmentation uses logical variable-size units matching program structure.", "MEDIUM")),
}
MARKS = {"MCQ": 2, "TRUE_FALSE": 1, "SHORT": 3, "DESCRIPTIVE": 5}

qid = 0
opt_id = 0
q_rows, o_rows = [], []
questions = {}  # qid -> dict(subject, type, marks, options[(id, correct)], text)
sub_questions = {}
for sid, b in bank.items():
    sub_questions[sid] = []

    def add_q(text, qtype, diff, model=None, opts=None, correct=None):
        global qid, opt_id
        qid += 1
        marks = MARKS[qtype]
        q_rows.append(f"({qid},{sid},{b['author']},{q(text)},{q(qtype)},{q(diff)},{marks},"
                      f"{q(model) if model else 'NULL'},'ACTIVE','2026-07-0{1 + (qid % 5)} 10:00:00')")
        oi = []
        if opts:
            for n, t in enumerate(opts):
                opt_id += 1
                o_rows.append(f"({opt_id},{qid},{q(t)},{1 if n == correct else 0},{n + 1})")
                oi.append((opt_id, n == correct))
        questions[qid] = dict(subject=sid, type=qtype, marks=marks, options=oi)
        sub_questions[sid].append(qid)

    for text, opts, c, d in b["mcq"]:
        add_q(text, "MCQ", d, opts=opts, correct=c)
    for text, ans, d in b["tf"]:
        add_q(text, "TRUE_FALSE", d, opts=["True", "False"], correct=0 if ans else 1)
    add_q(b["short"][0], "SHORT", b["short"][2], model=b["short"][1])
    add_q(b["desc"][0], "DESCRIPTIVE", b["desc"][2], model=b["desc"][1])

# one archived question for the filter demo
qid += 1
q_rows.append(f"({qid},1,2,'Which SQL keyword removes duplicate rows from a result set?','MCQ','EASY',2,NULL,'ARCHIVED','2026-07-03 10:00:00')")
for n, (t, c) in enumerate([("UNIQUE", 0), ("DISTINCT", 1), ("DIFFERENT", 0), ("SINGLE", 0)]):
    opt_id += 1
    o_rows.append(f"({opt_id},{qid},{q(t)},{c},{n + 1})")

emit("INSERT INTO questions (question_id, subject_id, created_by, question_text, question_type, difficulty, default_marks, model_answer, status, created_at) VALUES")
emit(",\n".join(q_rows) + ";\n")
emit("INSERT INTO question_options (option_id, question_id, option_text, is_correct, display_order) VALUES")
emit(",\n".join(o_rows) + ";\n")

# ---- examinations (each exam uses all 9 active questions of its subject: 5*2+2*1+3+5 = 20 marks)
exams = [
    # id, subject, owner, title, start, end, duration, max, pass, status
    (1, 1, 2, "DBMS Mid-Term Examination", "2026-09-15 10:00:00", "2026-09-15 11:00:00", 45, 20, 8, "COMPLETED"),
    (2, 2, 3, "DSA Unit Test 1", "2026-10-10 14:00:00", "2026-10-10 15:00:00", 45, 20, 8, "COMPLETED"),
    (3, 3, 4, "Operating Systems Quiz", "2026-11-05 11:00:00", "2026-11-05 12:00:00", 45, 20, 8, "SCHEDULED"),
    (4, 1, 2, "DBMS Practice Test (Draft)", "2026-11-12 10:00:00", "2026-11-12 11:00:00", 30, 20, 8, "DRAFT"),
]
emit("INSERT INTO examinations (exam_id, subject_id, created_by, title, description, scheduled_start, scheduled_end, duration_minutes, max_marks, passing_marks, status, created_at) VALUES")
emit(",\n".join(f"({e[0]},{e[1]},{e[2]},{q(e[3])},{q('Covers the full syllabus unit.')},{q(e[4])},{q(e[5])},{e[6]},{e[7]},{e[8]},{q(e[9])},'2026-08-20 09:00:00')"
                for e in exams) + ";\n")

eq_rows = []
eq_map = {}  # (exam, question) -> eq_id
eq_id = 0
exam_questions = {}
for e in exams:
    order = 0
    exam_questions[e[0]] = []
    qs = [x for x in sub_questions[e[1]]]
    if e[0] == 4:  # draft: only 5 of 9 assigned so far (marks do not yet reach max_marks)
        qs = qs[:5]
    for x in qs:
        order += 1
        eq_id += 1
        eq_map[(e[0], x)] = eq_id
        exam_questions[e[0]].append((eq_id, x))
        eq_rows.append(f"({eq_id},{e[0]},{x},{questions[x]['marks']},{order})")
emit("INSERT INTO examination_questions (exam_question_id, exam_id, question_id, marks, display_order) VALUES")
emit(",\n".join(eq_rows) + ";\n")

# ---- attempts + answers for exams 1 and 2
ability = [0.95, 0.85, 0.75, 0.65, 0.55, 0.45, 0.8, 0.35, 0.6, 0.9, 0.25, 0.7]
sample_text = {"SHORT": ["It is a minimal attribute set that identifies a tuple uniquely.", "A key that can identify rows.", "Candidate key is a column with unique values, e.g. enrollment number."],
               "DESCRIPTIVE": ["Detailed answer covering the main points with an example.", "Partial answer that covers only some of the points.", "Brief answer that mentions the key idea."]}
attempt_rows, answer_rows, pub_rows = [], [], []
attempt_id = 0
skip = {1: {8}, 2: {5, 8}}  # CSE students (index 0-8) who never attempted: feeds the "not attempted" demo query
for e in exams[:2]:
    ex = e[0]
    start0 = e[4]
    day = start0[:10]
    for si, s in enumerate(students):
        if si in skip[ex]:
            continue
        # IT students (idx 9..11) are not eligible for CSE exams, so they never attempt
        if s[5] != subjects[e[1] - 1][6]:
            continue
        attempt_id += 1
        auto = (ex == 1 and si == 7)
        st = f"{day} 10:{si:02d}:00" if ex == 1 else f"{day} 14:{si:02d}:00"
        en_min = 45 if auto else 20 + si * 2
        hh, mm = int(st[11:13]), int(st[14:16]) + en_min
        hh += mm // 60
        mm %= 60
        en = f"{day} {hh:02d}:{mm:02d}:00"
        attempt_rows.append(f"({attempt_id},{ex},{s[0]},{q(st)},{q(en)},{q('AUTO_SUBMITTED' if auto else 'SUBMITTED')})")
        for eqid, x in exam_questions[ex]:
            info = questions[x]
            if info["type"] in ("MCQ", "TRUE_FALSE"):
                if rng.random() < 0.06:
                    continue  # unanswered
                correct = [o for o, c in info["options"] if c][0]
                if rng.random() < ability[si]:
                    chosen = correct
                else:
                    chosen = rng.choice([o for o, c in info["options"] if not c])
                awarded = info["marks"] if chosen == correct else 0
                answer_rows.append(f"({attempt_id},{eqid},{chosen},NULL,{rng.choice([0, 0, 0, 1])},{awarded},'EVALUATED',NULL,{q(en)})")
            else:
                if rng.random() < 0.08:
                    continue
                text = rng.choice(sample_text[info["type"]])
                if ex == 1:  # fully evaluated by the faculty owner
                    mk = round(info["marks"] * min(1.0, max(0.0, ability[si] + rng.uniform(-0.15, 0.1))) * 2) / 2
                    answer_rows.append(f"({attempt_id},{eqid},NULL,{q(text)},0,{mk},'EVALUATED',{e[2]},'2026-09-17 16:00:00')")
                else:  # exam 2: evaluation still pending for most subjective answers
                    if si % 3 == 0:
                        mk = round(info["marks"] * ability[si] * 2) / 2
                        answer_rows.append(f"({attempt_id},{eqid},NULL,{q(text)},0,{mk},'EVALUATED',{e[2]},'2026-10-12 11:00:00')")
                    else:
                        answer_rows.append(f"({attempt_id},{eqid},NULL,{q(text)},0,NULL,'PENDING',NULL,NULL)")

emit("INSERT INTO exam_attempts (attempt_id, exam_id, student_id, started_at, submitted_at, status) VALUES")
emit(",\n".join(attempt_rows) + ";\n")
emit("INSERT INTO student_answers (attempt_id, exam_question_id, selected_option_id, answer_text, marked_for_review, awarded_marks, evaluation_status, evaluated_by, evaluated_at) VALUES")
emit(",\n".join(answer_rows) + ";\n")

emit("INSERT INTO result_publications (exam_id, published_by, action, note, published_at) VALUES")
emit("(1,2,'PUBLISH','Mid-term results released after full evaluation','2026-09-18 10:00:00'),")
emit("(1,2,'CORRECTION','Q9 descriptive marks corrected after re-evaluation request','2026-09-20 12:30:00');\n")

emit("INSERT INTO audit_logs (actor_user_id, action, entity_type, entity_id, details, created_at) VALUES")
emit("(1,'USER_CREATED','user',2,JSON_OBJECT('role','FACULTY'),'2026-07-01 09:00:00'),")
emit("(1,'SUBJECT_CREATED','subject',1,JSON_OBJECT('code','CS301'),'2026-07-01 09:10:00'),")
emit("(2,'EXAM_CREATED','examination',1,JSON_OBJECT('title','DBMS Mid-Term Examination'),'2026-08-20 09:00:00'),")
emit("(2,'RESULTS_PUBLISHED','examination',1,JSON_OBJECT('students',9),'2026-09-18 10:00:00'),")
emit("(2,'RESULT_CORRECTED','examination',1,JSON_OBJECT('reason','re-evaluation'),'2026-09-20 12:30:00');")

Path(__file__).resolve().parent.parent.joinpath("02_seed.sql").write_text("\n".join(out) + "\n")
print(f"questions={qid} options={opt_id} attempts={attempt_id} answers={len(answer_rows)}")
